#!/usr/bin/env node
/**
 * Generates src-tauri/src/menu_i18n.rs from frontend/i18n/*.js so the native
 * menu bar / tray menu can be localized in Rust using the OS locale, without
 * waiting for the webview to push translations. Run after editing i18n files:
 *   node scripts/gen-menu-i18n.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const I18N_DIR = path.join(ROOT, "frontend", "i18n");
const OUT = path.join(ROOT, "src-tauri", "src", "menu_i18n.rs");

const MENU_KEYS = [
  "about.title", "menu.settings", "diagram.pie", "menu.galaxy", "diagram.treemap",
  "lang.auto", "lang.label", "menu.language", "menu.view",
  "tools.scan_downloads", "tools.scan_trash", "trash.title", "menu.find_files",
  "menu.empty_folders", "menu.cleanup_downloads", "smart.title", "menu.browser_tools",
  "menu.apfs_snapshots", "tools.find_duplicates", "menu.export_html",
  "menu.preferences", "menu.clear_scan", "tools.empty_trash", "menu.exit",
  "menu.tools", "menu.window", "menu.check_updates", "menu.help",
  "menu.tray_open", "menu.tray_last_scan",
];

function loadLocale(code) {
  const src = fs.readFileSync(path.join(I18N_DIR, `${code}.js`), "utf8");
  const m = src.match(/window\.I18N_DATA\["[^"]+"\]\s*=\s*(\{.*\});\s*$/s);
  if (!m) throw new Error(`cannot parse ${code}.js`);
  return JSON.parse(m[1]);
}

const codes = [];
const tables = {};
for (const f of fs.readdirSync(I18N_DIR).filter((f) => f.endsWith(".js"))) {
  const code = f.slice(0, -3);
  codes.push(code);
  tables[code] = loadLocale(code);
}
codes.sort();

function rustEscape(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

let rs = `// @generated by scripts/gen-menu-i18n.mjs — do not edit by hand.
// Native menu / tray translations keyed by base locale code. Values come from
// frontend/i18n/*.js (the single source of truth).

pub fn menu_labels(code: &str) -> &'static [(&'static str, &'static str)] {
    match code {
`;
for (const code of codes) {
  const pairs = MENU_KEYS.map((k) => {
    const v = tables[code][k];
    return `            ("${k}", "${rustEscape(v ?? "")}")`;
  });
  rs += `        "${code}" => &[\n${pairs.join(",\n")},\n        ],\n`;
}
rs += `        _ => &[],
    }
}
`;

fs.writeFileSync(OUT, rs);
console.log(`[gen-menu-i18n] wrote ${OUT} (${codes.length} locales, ${MENU_KEYS.length} keys)`);
